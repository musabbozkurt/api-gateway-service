CREATE SCHEMA IF NOT EXISTS delivery;

CREATE TABLE IF NOT EXISTS delivery.person
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255),
    email               VARCHAR(255) NOT NULL,
    registration_number VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS delivery.delivery
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_man_id BIGINT    NOT NULL,
    customer_id     BIGINT    NOT NULL,
    start_time      TIMESTAMP NOT NULL,
    end_time        TIMESTAMP NOT NULL,
    distance        BIGINT,
    price           BIGINT,
    comission       BIGINT,
    CONSTRAINT fk_delivery_delivery_man FOREIGN KEY (delivery_man_id) REFERENCES delivery.person (id) ON DELETE CASCADE,
    CONSTRAINT fk_delivery_customer FOREIGN KEY (customer_id) REFERENCES delivery.person (id) ON DELETE CASCADE
);
