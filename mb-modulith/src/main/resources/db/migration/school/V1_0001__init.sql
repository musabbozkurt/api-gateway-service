create schema if not exists school_registration;

CREATE SCHEMA IF NOT EXISTS school;
create table if not exists school.course
(
    course_id          bigint       not null GENERATED BY DEFAULT AS IDENTITY,
    created_date_time  timestamp    not null,
    modified_date_time timestamp    not null,
    deleted            boolean      not null default false,
    course_details     varchar(255) not null,
    course_duration    varchar(255) not null,
    course_name        varchar(255) not null,
    constraint course_id_pkey primary key (course_id)
);

create table if not exists school.student
(
    student_id         bigint       not null GENERATED BY DEFAULT AS IDENTITY,
    created_date_time  timestamp    not null,
    modified_date_time timestamp    not null,
    deleted            boolean      not null default false,
    address            varchar(255) not null,
    mobile_number      varchar(255) not null,
    student_name       varchar(255) not null,
    constraint student_id_pkey primary key (student_id)
);
create table if not exists school.student_course
(
    student_id bigint not null,
    course_id  bigint not null
);

